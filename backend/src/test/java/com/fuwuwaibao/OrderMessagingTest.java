package com.fuwuwaibao;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fuwuwaibao.entity.OrderCreatedEvent;
import com.fuwuwaibao.service.OrderEventService;
import com.fuwuwaibao.service.OrderNotificationConsumer;
import com.fuwuwaibao.service.OrderOutboxPublisher;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.JdbcTest;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.boot.test.mock.mockito.SpyBean;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.kafka.core.KafkaTemplate;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

import java.util.concurrent.CompletableFuture;

import static org.assertj.core.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

@JdbcTest(properties = {"spring.sql.init.mode=never", "spring.datasource.generate-unique-name=true"})
@Import({OrderEventService.class, OrderMessagingTest.JsonConfig.class})
@Transactional(propagation = Propagation.NOT_SUPPORTED)
class OrderMessagingTest {
    @Autowired JdbcTemplate jdbc;
    @Autowired OrderEventService orders;
    @SpyBean ObjectMapper json;

    @TestConfiguration
    static class JsonConfig {
        @Bean ObjectMapper objectMapper() { return new ObjectMapper(); }
    }

    @BeforeEach
    void prepare() {
        reset(json);
        jdbc.execute("SET MODE MySQL");
        jdbc.execute("DROP TABLE IF EXISTS shopping_order");
        jdbc.execute("DROP TABLE IF EXISTS order_event_outbox");
        jdbc.execute("DROP TABLE IF EXISTS order_notification");
        jdbc.execute("CREATE TABLE shopping_order(id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                "userid INT,shoppingid INT,address_id INT,isDefault VARCHAR(10),isBuy VARCHAR(20))");
        jdbc.execute("CREATE TABLE order_event_outbox(event_id VARCHAR(36) PRIMARY KEY,order_id INT,payload VARCHAR(4000)," +
                "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,sent_at TIMESTAMP,attempts INT DEFAULT 0)");
        jdbc.execute("CREATE TABLE order_notification(event_id VARCHAR(36) PRIMARY KEY,order_id INT,user_id INT,message VARCHAR(255))");
    }

    @Test
    void savesOrderAndDurableEventTogetherWithoutKafka() {
        assertThat(orders.createOrder(2, 1, 1, "false", "待确认")).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM order_event_outbox WHERE sent_at IS NULL", Integer.class)).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT order_id FROM order_event_outbox", Integer.class))
                .isEqualTo(jdbc.queryForObject("SELECT id FROM shopping_order", Integer.class));
    }

    @Test
    void rollsBackOrderWhenEventCannotBeSaved() throws Exception {
        doThrow(new JsonProcessingException("test serialization failure") {}).when(json).writeValueAsString(any());
        assertThatThrownBy(() -> orders.createOrder(2, 1, 1, "false", "待确认"))
                .isInstanceOf(IllegalStateException.class);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM shopping_order", Integer.class)).isZero();
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM order_event_outbox", Integer.class)).isZero();
    }

    @Test
    void duplicateDeliveryCreatesOneNotification() throws Exception {
        OrderNotificationConsumer consumer = new OrderNotificationConsumer(jdbc, json);
        String payload = json.writeValueAsString(new OrderCreatedEvent("repeat-event", 10, 2, 1));
        consumer.consume(payload);
        consumer.consume(payload);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM order_notification", Integer.class)).isEqualTo(1);
    }

    @Test
    @SuppressWarnings("unchecked")
    void kafkaFailureKeepsEventPendingAndLaterRetryPublishesIt() {
        JdbcTemplate db = mock(JdbcTemplate.class);
        KafkaTemplate<String, String> kafka = mock(KafkaTemplate.class);
        when(db.queryForList(anyString())).thenReturn(java.util.List.of(
                java.util.Map.of("event_id", "retry-event", "order_id", 10, "payload", "{}")));
        when(kafka.send("orders", "10", "{}"))
                .thenReturn(CompletableFuture.failedFuture(new RuntimeException("broker offline")))
                .thenReturn(CompletableFuture.completedFuture(null));
        OrderOutboxPublisher publisher = new OrderOutboxPublisher(db, kafka, "orders");
        publisher.publishPending();
        verify(db, never()).update(contains("sent_at=CURRENT_TIMESTAMP"), eq("retry-event"));
        publisher.publishPending();
        verify(db).update(contains("sent_at=CURRENT_TIMESTAMP"), eq("retry-event"));
    }
}
